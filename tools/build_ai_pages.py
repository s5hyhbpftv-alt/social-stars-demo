def render_special(sp):
    k = sp["kind"]
    if k == "table":
        head = "".join(f"<th>{e(h)}</th>" for h in sp["head"])
        rows = "".join("<tr>" + "".join((f"<td><b>{e(c)}</b></td>" if i == 0 else f"<td>{e(c)}</td>") for i, c in enumerate(r)) + "</tr>" for r in sp["rows"])
        return f'<div class="tbl-wrap reveal"><table><thead><tr>{head}</tr></thead><tbody>{rows}</tbody></table></div>'
    if k == "flow":
        return '<div class="flow reveal">' + "".join(f"<div><b>{e(a)}</b><span>{e(b)}</span></div>" for a, b in sp["items"]) + "</div>"
    if k == "levels":
        return '<div class="levels reveal">' + "".join(f"<div><i>{e(a)}</i><b>{e(b)}</b><span>{e(c)}</span></div>" for a, b, c in sp["items"]) + "</div>"
    if k == "cards":
        return '<div class="cards reveal">' + "".join(f'<div class="card"><h3>{e(a)}</h3><p>{e(b)}</p></div>' for a, b in sp["items"]) + "</div>"
    if k == "radar":
        bars = "".join(f'<div class="bar"><span>{e(n)}</span><div class="track"><div class="fill" data-w="{v}"></div></div><span class="v">{v}</span></div>' for n, v in sp["items"])
        return (f'<div class="radar reveal" style="max-width:720px;color:var(--ink)" aria-label="Пример отчёта: индекс AI-видимости">'
                f'<h4>Индекс AI-видимости</h4><p class="sub">Пример формата отчёта · демо-данные</p>{bars}'
                f'<div class="legend"><span>Упоминаемость · точность · тональность</span><span>0–100</span></div></div>')
    raise ValueError(k)


